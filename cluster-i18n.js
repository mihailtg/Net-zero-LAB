  function getLanguage() {
    if (typeof root.getLanguage === 'function') return root.getLanguage() === 'bg' ? 'bg' : 'en';
    return root.document?.documentElement?.getAttribute('data-lang') === 'bg' ? 'bg' : 'en';
  }

  function t(key, variables = {}, language = getLanguage()) {
    const template = COPY[language]?.[key] ?? COPY.en[key] ?? key;
    return Object.entries(variables).reduce(
      (text, [name, value]) => text.replaceAll(`{${name}}`, String(value)),
      template
    );
  }

  function localize(value, language = getLanguage()) {
    if (value && typeof value === 'object') return value[language] || value.en || value.bg || '';
    return String(value ?? '');
  }

  return Object.freeze({ COPY, getLanguage, t, localize });
