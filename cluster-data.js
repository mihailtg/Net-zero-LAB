  function clampScore20(value) {
    const numeric = Number(value);
    if (!Number.isFinite(numeric)) return 0;
    return Math.max(0, Math.min(VISUAL_SCALE_MAX, numeric));
  }

  function createFactorProfile(score20, metric, seed) {
    const target = clampScore20(score20);
    const count = metric.factors.length;
    const rawOffsets = metric.factors.map((_, index) => (((seed * 17 + index * 11) % 13) - 6) * 0.18);
    const offsetMean = rawOffsets.reduce((sum, value) => sum + value, 0) / count;
    const adjusted = rawOffsets.map((offset) => clampScore20(target + offset - offsetMean));
    for (let pass = 0; pass < 8; pass += 1) {
      const currentMean = adjusted.reduce((sum, value) => sum + value, 0) / count;
      const residual = target - currentMean;
      if (Math.abs(residual) < 0.000001) break;
      const adjustable = adjusted
        .map((value, index) => ({ value, index }))
        .filter((entry) => residual > 0 ? entry.value < VISUAL_SCALE_MAX : entry.value > 0);
      if (!adjustable.length) break;
      adjustable.forEach((entry) => {
        adjusted[entry.index] = clampScore20(entry.value + residual * count / adjustable.length);
      });
    }
    return Object.fromEntries(metric.factors.map((factor, index) => [factor.key, adjusted[index] / VISUAL_SCALE_MAX]));
  }

